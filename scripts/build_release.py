#!/usr/bin/env python3
"""Build OMEGA Modus v1.0.0 adapter bundles and release archives safely."""
from __future__ import annotations

import hashlib
import shutil
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VERSION = "1.0.0"
DIST_ROOT = ROOT / "dist"
OUTPUT = DIST_ROOT / f"omega-modus-v{VERSION}"
MARKER = ".omegamodus-generated-by-build_release.py"
SKILL = ROOT / "skills" / "omega-modus"

SKILL_REF = (
    "Use the OMEGA Modus skill for non-trivial work. Choose QUICK, STANDARD, or DEEP rigor "
    "based on task complexity and consequence. Follow SCAN, VERIFY, THINK, STRATEGIZE, "
    "EXECUTE, VALIDATE, and REPORT without forcing them into visible output. Select only "
    "applicable quality methods. Never fabricate evidence, tests, tool results, memory, or "
    "completed actions. Respect platform permissions and obtain approval before consequential "
    "or irreversible external actions. Provide concise rationale and audit-relevant results, "
    "not private chain-of-thought. Keep simple tasks simple."
)

ADAPTERS = (
    "codex",
    "claude-code",
    "gemini-cli",
    "cursor",
    "github-copilot",
    "chatgpt",
    "generic",
)


def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content.strip() + "\n", encoding="utf-8")


def copy_skill(destination: Path) -> None:
    if not (SKILL / "SKILL.md").is_file():
        raise SystemExit(f"Canonical skill not found: {SKILL}")
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(SKILL, destination, dirs_exist_ok=True)


def prepare_output() -> None:
    DIST_ROOT.mkdir(parents=True, exist_ok=True)
    if OUTPUT.exists():
        marker = OUTPUT / MARKER
        if not marker.is_file():
            raise SystemExit(
                f"Refusing to remove {OUTPUT}: generation marker is missing. "
                "Move or rename that directory yourself, then rebuild."
            )
        shutil.rmtree(OUTPUT)
    OUTPUT.mkdir(parents=True)
    write(OUTPUT / MARKER, f"Generated by scripts/build_release.py for OMEGA Modus v{VERSION}.")


def build_bundles() -> None:
    bundles = OUTPUT / "bundles"

    # Codex: project guidance and an on-demand Agent Skill.
    codex = bundles / "codex"
    write(
        codex / "AGENTS.md",
        f"""# OMEGA Modus Project Guidance

{SKILL_REF}

For detailed workflows, use the `omega-modus` Agent Skill in `.agents/skills/omega-modus/`. 
Merge this section into an existing AGENTS.md rather than replacing unrelated project guidance.
""",
    )
    copy_skill(codex / ".agents" / "skills" / "omega-modus")
    write(codex / "README.txt", "Copy AGENTS.md into the project root (merge if one exists) and copy .agents/skills/omega-modus/ into the project's .agents/skills/ directory. Start a new Codex session and invoke $omega-modus when needed.\n")

    # Claude Code: project Agent Skill.
    claude = bundles / "claude-code"
    copy_skill(claude / ".claude" / "skills" / "omega-modus")
    write(claude / "README.txt", "Copy .claude/skills/omega-modus/ into the target project's .claude/skills/ directory. Start or refresh Claude Code, then invoke /omega-modus or let the skill be selected for a matching task.\n")

    # Gemini CLI: persistent GEMINI.md and Agent Skill in the shared discovery alias.
    gemini = bundles / "gemini-cli"
    write(
        gemini / "GEMINI.md",
        f"""# OMEGA Modus

{SKILL_REF}

For detailed workflows, use the `omega-modus` Agent Skill in `.agents/skills/omega-modus/` where supported by the installed Gemini CLI version. Merge this section into an existing GEMINI.md rather than replacing unrelated project context.
""",
    )
    copy_skill(gemini / ".agents" / "skills" / "omega-modus")
    write(gemini / "README.txt", "Merge GEMINI.md into the project root and copy .agents/skills/omega-modus/ into the project skill directory. Restart the CLI or reload skills with /skills reload; verify with /skills list. Check your Gemini CLI version's supported skill locations.\n")

    # Cursor: native project rule using .mdc frontmatter.
    cursor = bundles / "cursor"
    write(
        cursor / ".cursor" / "rules" / "omega-modus.mdc",
        f"""---
description: Apply the OMEGA Modus precision workflow proportionately to meaningful tasks. Use for non-trivial, ambiguous, consequential, or hard-to-reverse work; skip for trivial requests.
alwaysApply: false
---

{SKILL_REF}

For complex, ambiguous, consequential, or hard-to-reverse tasks: define acceptance criteria; compare materially different approaches; identify a principal failure risk and mitigation; select only applicable methods from PDCA/PDSA, Five Whys, Ishikawa, Poka-Yoke, FMEA, Pareto, A3, and Kaizen; execute with reviewable changes; verify actual results.

Do not over-process simple requests. Do not expose private chain-of-thought. Distinguish facts, inferences, and assumptions when material. Treat possible causes as hypotheses until supported. Do not claim tests or tool actions that were not performed. Follow platform permissions and ask before consequential external or irreversible actions.
""",
    )
    write(cursor / "README.txt", "Copy .cursor/rules/omega-modus.mdc into the target project's .cursor/rules/ directory. Confirm the rule is enabled in Cursor. If a rule of this name already exists, review and merge manually.\n")

    # GitHub Copilot: repository instructions plus its Agent Skill discovery path.
    copilot = bundles / "github-copilot"
    write(
        copilot / ".github" / "copilot-instructions.md",
        f"""# OMEGA Modus

{SKILL_REF}

For recurring defects, investigate evidence before naming a root cause. Use Five Whys or Ishikawa when appropriate, Poka-Yoke for prevention, PDCA for measured improvement, and FMEA for consequential changes. Use Pareto only with adequate categorized observations. Never turn hypotheses into facts or generate unsupported statistics. Keep simple tasks simple. Report checks honestly and respect user approval and platform permission boundaries. Do not reveal private chain-of-thought.

For specialized workflows, use the OMEGA Modus Agent Skill in `.github/skills/omega-modus/` where Agent Skills are supported.
""",
    )
    copy_skill(copilot / ".github" / "skills" / "omega-modus")
    write(copilot / "README.txt", "Copy .github/copilot-instructions.md into the repository's .github/ directory and .github/skills/omega-modus/ into the repository. Check the Copilot client/feature's support for repository instructions and Agent Skills.\n")

    # ChatGPT: skill bundle for Skills-enabled surfaces and a manual fallback.
    chatgpt = bundles / "chatgpt"
    copy_skill(chatgpt / "skill" / "omega-modus")
    write(
        chatgpt / "instructions.md",
        f"""# OMEGA Modus — ChatGPT Instructions

{SKILL_REF}

Use this in the relevant user/project instruction field where supported, or paste it at the start of a conversation. For detailed quality methods and workflows, install the accompanying `skill/omega-modus/` folder where Skills are supported. Do not assume every ChatGPT surface supports persistent local skills or global custom instructions.
""",
    )
    write(chatgpt / "README.txt", "For a Skills-enabled ChatGPT environment, install the skill folder using the product's supported skill workflow. Otherwise paste instructions.md into the relevant custom-instruction or project-instruction field, or at the start of a conversation. Availability varies by product surface and plan.\n")

    # Generic: self-contained prompt including the complete core and all method/safety references.
    generic = bundles / "generic"
    parts = [
        "# OMEGA Modus — Universal AI Precision Protocol\n\nApply the framework proportionately; do not force every stage into visible output.\n",
        (SKILL / "references" / "CORE_PROTOCOL.md").read_text(encoding="utf-8"),
        (SKILL / "references" / "QUALITY_INTELLIGENCE.md").read_text(encoding="utf-8"),
        (SKILL / "references" / "SAFETY_AND_TRUST.md").read_text(encoding="utf-8"),
        (SKILL / "references" / "WORKFLOWS.md").read_text(encoding="utf-8"),
    ]
    write(generic / "OMEGA-MODUS-PROMPT.md", "\n\n---\n\n".join(parts))
    write(generic / "README.txt", "Paste OMEGA-MODUS-PROMPT.md into the system/project instruction field of your assistant when supported, or paste it into a conversation. Persistent behavior depends on the target product.\n")

    # Include the license and concise bundle index for redistribution.
    for name in ADAPTERS:
        bundle = bundles / name
        shutil.copy2(ROOT / "LICENSE", bundle / "LICENSE")
        shutil.copy2(ROOT / "NOTICE", bundle / "NOTICE")
        write(
            bundle / "BUNDLE.txt",
            f"OMEGA Modus v{VERSION} — {name} adapter\n\nThis adapter is part of the OMEGA Modus Universal AI Precision Protocol. See LICENSE and the adapter README for use and limitations.\n",
        )


def zip_directory(source: Path, destination: Path, arc_prefix: str | None = None) -> None:
    destination.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(destination, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as zf:
        for path in sorted(p for p in source.rglob("*") if p.is_file()):
            if "__pycache__" in path.parts or path.suffix in {".pyc", ".pyo"}:
                continue
            arcname = Path(arc_prefix) / path.relative_to(source) if arc_prefix else path.relative_to(source)
            zf.write(path, arcname.as_posix())


def build_archives() -> None:
    archives = OUTPUT / "archives"
    bundles = OUTPUT / "bundles"
    for name in ADAPTERS:
        zip_directory(bundles / name, archives / f"omega-modus-v{VERSION}-{name}.zip", name)

    # Complete source archive; exclude generated dist output, VCS metadata and bytecode.
    source_tmp = OUTPUT / "source-tree"
    source_tmp.mkdir(parents=True, exist_ok=True)
    excluded = {".git", ".venv", "venv", "__pycache__", "dist"}
    for path in ROOT.rglob("*"):
        if not path.is_file() or any(part in excluded for part in path.relative_to(ROOT).parts):
            continue
        relative = path.relative_to(ROOT)
        if relative.suffix in {".pyc", ".pyo"}:
            continue
        destination = source_tmp / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, destination)
    zip_directory(source_tmp, archives / f"omega-modus-v{VERSION}-source.zip", "omega-modus")
    shutil.rmtree(source_tmp)

    # The checksum manifest covers each individual adapter ZIP and the source ZIP.
    # The convenience archive contains that manifest plus the seven adapter ZIPs.
    individual_archives = sorted(
        path for path in archives.glob("omega-modus-v*.zip")
        if path.name != f"omega-modus-v{VERSION}-all-platform-bundles.zip"
    )
    lines = []
    for path in individual_archives:
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        lines.append(f"{digest}  {path.name}")
    sums_path = OUTPUT / "SHA256SUMS.txt"
    write(sums_path, "\n".join(lines))

    all_bundles = archives / f"omega-modus-v{VERSION}-all-platform-bundles.zip"
    with zipfile.ZipFile(all_bundles, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as zf:
        for path in sorted(archives.glob(f"omega-modus-v{VERSION}-*.zip")):
            if path.name in {f"omega-modus-v{VERSION}-source.zip", all_bundles.name}:
                continue
            zf.write(path, f"platform-zips/{path.name}")
        zf.write(sums_path, "SHA256SUMS.txt")


def main() -> None:
    if not (SKILL / "SKILL.md").is_file():
        raise SystemExit(f"Canonical skill not found: {SKILL}")
    prepare_output()
    build_bundles()
    build_archives()
    print(f"Built OMEGA Modus v{VERSION} in: {OUTPUT}")
    print("Adapter bundles:")
    for name in ADAPTERS:
        print(f" - {name}")
    print(f"Archives: {OUTPUT / 'archives'}")
    print("Note: this builds local release artifacts; it does not publish to a GitHub account.")


if __name__ == "__main__":
    main()
